import re
import sys

NETLIST = "/home/zcz/verda/autoDecodeChip/pnr/amechip/results/sky130hd/amechip/p4a4fix/6_final.v"
OUT = "/home/zcz/verda/autoDecodeChip/tb/gate/p4b3_gate_probes.vh"

MEMC = r"u_mem.u_core.u_memc"
CPU = r"u_cpu"

VECS = [
    (MEMC, "st_q", 3),
    (MEMC, "hw0_q", 16),
    (MEMC, "rq_rp", 2),
    (MEMC, "rq_wp", 2),
    (MEMC, "rq_cnt", 3),
    (MEMC, "wq_rp", 2),
    (MEMC, "wq_wp", 2),
    (MEMC, "wq_cnt", 3),
    (MEMC, "ws_cnt", 3),
    (MEMC, "r_valid_o", 1),
    (MEMC, "last_wr_q", 1),
    (CPU, "ax_r_data", 32),
    (CPU, "ax_r_valid", 1),
    ("u_mem.u_core.u_xbar.g_ports[8].u_port", "r_state", 2),
    ("u_mem.u_core.u_xbar.g_ports[8].u_port", "r_l_addr", 4),
    (MEMC, "ar_addr_i", 4),
]

RAW = ["_035551_", "_064887_", "net19822", "_064891_", "net38",
       "_035582_", "net33615", "_064905_", "net54",
       "net53", "net49",
       "_035589_", "_064894_", "_064893_", "_035577_", "net27144", "net26535", "net19451"]
ARRAYS = [
    (MEMC, "rq_addr", 23, 4),
    (MEMC, "wq_data", 32, 4),
]


def main():
    text = open(NETLIST, encoding="utf-8", errors="replace").read()
    declared = set(re.findall(r"wire \\(.*?) ;", text))
    out = ["// auto-generated by p4b3_gen_probes.py — P4B3 门级层次探针(勿手改)"]
    missing = []

    def bitname(sig, bit):
        return f"{sig}[{bit}]"

    for prefix, sig, width in VECS:
        if width == 1:
            if f"{prefix}.{sig}" not in declared:
                missing.append(f"{prefix}.{sig}")
                continue
            out.append(f"wire P_{sig.replace('[','').replace(']','')} = dut.\\{prefix}.{sig} ;")
            continue
        refs = []
        for b in range(width):
            short = bitname(sig, b)
            nm = f"{prefix}.{short}"
            if nm not in declared:
                missing.append(nm)
                continue
            refs.append(f"P_{sig}_{b}")
            out.append(f"wire P_{sig}_{b} = dut.\\{prefix}.{short} ;")
        if len(refs) == width:
            msb_first = ", ".join(f"P_{sig}_{b}" for b in range(width - 1, -1, -1))
            out.append(f"wire [{width-1}:0] P_{sig} = {{{msb_first}}};")
        elif width > 1 and not missing:
            missing.append(f"{prefix}.{sig}(partial)")

    for prefix, sig, width, slots in ARRAYS:
        for k in range(slots):
            refs = []
            for b in range(width):
                full = f"{prefix}.{sig}[{k}][{b}]"
                if full not in declared:
                    missing.append(full)
                    continue
                refs.append(f"P_{sig}_{k}_{b}")
                out.append(f"wire P_{sig}_{k}_{b} = dut.\\{prefix}.{sig}[{k}][{b}] ;")
            if len(refs) == width:
                msb_first = ", ".join(f"P_{sig}_{k}_{b}" for b in range(width - 1, -1, -1))
                out.append(f"wire [{width-1}:0] P_{sig}_{k} = {{{msb_first}}};")

    if missing:
        print("MISSING probe signals in netlist:")
        for m in missing:
            print("  ", m)
        sys.exit(1)
    for arr in ("rq_addr", "wq_addr"):
        for slot in range(4):
            for bit in (0, 1):
                nm = f"{MEMC}.{arr}[{slot}][{bit}]"
                if nm not in declared:
                    print(f"MISSING xinit signal: {nm}")
                    sys.exit(1)
    xinit = ["// auto-generated by p4b3_gen_probes.py — P4B3 XINIT 上电初值注入(勿手改)",
             "// 只 force 队列槽 bit[1:0](4B 对齐协议恒 0;泄露位=bit1);地址位 [22:2] 保持真实寄存器值",
             "// 用法:-DXINIT 编译 tb_p4b3_probe.sv / +XINIT 传 tb_p4b3_gate.sv"]
    for arr in ("rq_addr", "wq_addr"):
        for slot in range(4):
            for bit in (0, 1):
                xinit.append(f"force dut.\\{MEMC}.{arr}[{slot}][{bit}] = 1'b0 ;")
    with open("/home/zcz/verda/autoDecodeChip/tb/gate/p4b3_xinit.vh", "w") as f:
        f.write("\n".join(xinit) + "\n")
    declared_plain = set(re.findall(r"wire\s+([\\]?\S+)\s*;", text))
    for nm in RAW:
        if nm not in declared_plain and ("\\" + nm) not in declared_plain:
            print(f"MISSING raw net: {nm}")
            sys.exit(1)
        out.append(f"wire C_{nm.strip('_').lower() or nm} = dut.{nm} ;")
    out.append("wire P_dutpin3 = dut.xmem_a_o[3] ;")
    out.append("wire P_dutpin0 = dut.xmem_a_o[0] ;")
    out.append("wire P_dutpin1 = dut.xmem_a_o[1] ;")
    for k in (4, 5):
        if f"{MEMC}.st_q[{k}]" not in declared:
            print(f"MISSING st_q[{k}]"); sys.exit(1)
        out.append(f"wire P_st_q_{k} = dut.\\{MEMC}.st_q[{k}] ;")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"OK: {len(out)-1} probe refs -> {OUT}")


if __name__ == "__main__":
    main()
